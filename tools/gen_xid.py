#!/usr/bin/env python3
"""Generate full Unicode 15.1 XID tables for lusd_spec_codecs.c from Lean.

Reads verif/lean/UsdSpec/Unicode/XidTable.lean ranges (667 Start + 776
Continue) and emits C tables + binary-search lspec_is_xid_* into the
codecs sources. The generated XID code is numeric-only (not in c2lean
FUNCTIONS; global const tables await MiniC table support).

Usage:
    python3 tools/gen_xid.py [--check]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEAN = os.path.join(ROOT, "verif", "lean", "UsdSpec", "Unicode", "XidTable.lean")
LUSD_DIR = os.environ.get("LUSD_SPEC_DIR", os.path.expanduser("~/work/lightusd-c"))
DST = os.path.join(LUSD_DIR, "src", "internal", "lusd_spec_codecs.c")
TPL = os.path.join(ROOT, "tools", "templates", "lusd_spec_codecs.c")

PAIR_RE = re.compile(r"\(\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+)\s*\)")


def parse(lean_text):
    start_m = re.search(r"def xidStartRanges.*?#\[(.*?)\]\n", lean_text, re.S)
    cont_m = re.search(r"def xidContinueRanges.*?#\[(.*?)\]\n", lean_text, re.S)
    if not start_m or not cont_m:
        raise RuntimeError("XID ranges not found")
    start = [(int(a, 16), int(b, 16)) for a, b in PAIR_RE.findall(start_m.group(1))]
    cont = [(int(a, 16), int(b, 16)) for a, b in PAIR_RE.findall(cont_m.group(1))]
    for tbl, name in [(start, "Start"), (cont, "Continue")]:
        for lo, hi in tbl:
            if lo > hi:
                raise RuntimeError(f"{name}: inverted {lo:#x}-{hi:#x}")
        for (_, h1), (l2, _) in zip(tbl, tbl[1:]):
            if not h1 < l2:
                raise RuntimeError(f"{name}: unsorted at {h1:#x} {l2:#x}")
    return start, cont


def emit_table(var, pairs):
    lines = []
    lines.append(f"static const uint32_t {var}[][2] = {{")
    for lo, hi in pairs:
        lines.append(f"    {{0x{lo:X}u, 0x{hi:X}u}},")
    lines.append("};")
    return "\n".join(lines)


def emit_search(name, var, count):
    return f"""static uint32_t {name}_ranges(uint32_t cp) {{
    uint32_t lo;
    uint32_t hi;
    lo = 0;
    hi = {count}u;
    while (lo < hi) {{
        uint32_t mid;
        mid = (lo + hi) / 2;
        if (cp < {var}[mid][0]) {{
            hi = mid;
        }} else {{
            lo = mid + 1;
        }}
    }}
    if (lo == 0) {{
        return 0;
    }}
    if ({var}[lo - 1][0] <= cp) {{
        if (cp <= {var}[lo - 1][1]) {{
            return 1;
        }}
    }}
    return 0;
}}

uint32_t {name}(uint32_t cp) {{
    return {name}_ranges(cp);
}}"""


def emit(start, cont):
    lines = []
    lines.append("/* XID tables generated by tools/gen_xid.py from XidTable.lean — DO NOT EDIT (tables). */")
    lines.append(emit_table("kXidStart", start))
    lines.append(emit_table("kXidContinue", cont))
    lines.append(emit_search("lspec_is_xid_start", "kXidStart", len(start)))
    lines.append(emit_search("lspec_is_xid_continue", "kXidContinue", len(cont)))
    return "\n\n".join(lines) + "\n"


def patch(path, new_xid):
    text = open(path).read()
    start_marker = "uint32_t lspec_is_xid_start(uint32_t cp) {"
    idx = text.find(start_marker)
    if idx < 0:
        raise RuntimeError(f"{path}: XID stub not found")
    # Stub runs to EOF minus final newline? Replace from idx to end.
    head = text[:idx]
    return head + new_xid


def main():
    lean_text = open(LEAN).read()
    start, cont = parse(lean_text)
    print(f"gen_xid: Start {len(start)} Continue {len(cont)}", file=sys.stderr)
    new_xid = emit(start, cont)
    if "--check" in sys.argv:
        with open(DST) as f:
            cur = patch(DST, new_xid)
            # compare current file's XID section
            cur_text = open(DST).read()
            if new_xid not in cur_text:
                print("gen_xid: tables drift; run tools/gen_xid.py", file=sys.stderr)
                return 1
        print("gen_xid: ok")
        return 0
    for p in [DST, TPL]:
        if os.path.exists(p):
            new_text = patch(p, new_xid)
            open(p, "w").write(new_text)
            print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
